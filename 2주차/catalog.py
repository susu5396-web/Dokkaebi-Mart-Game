def build_catalog():
    products = {}
    for category, groups in enumerate(GROUPS):
        names = NAMES[category].split('|')
        assert len(names) == 32
        index = 0
        for group, icon, count in groups:
            for _ in range(count):
                pid = f'{category}-{index:02}'
                products[pid] = Product(pid, names[index], category, group, icon)
                index += 1
    return products


PRODUCTS = build_catalog()
